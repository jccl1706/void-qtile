#!/usr/bin/env bash
# =============================================================================
# theme.sh - one palette file, fanned out to everything that cannot read it
# =============================================================================
#
# Usage:  bin/theme.sh                 regenerate from the current theme
#         bin/theme.sh set nord        switch theme and regenerate
#         bin/theme.sh list            what themes exist
#         bin/theme.sh show            the current palette, resolved
#         bin/theme.sh --dry-run ...   print what would be written
#
# THE PALETTE LIVES IN themes/<name>.conf AND NOWHERE ELSE. foot, dunst and
# GTK each have their own config syntax and none of them can read another's,
# so before this script the same sixteen hex values were written out by hand
# in four files with a comment in each saying "keep this in step". That
# instruction is the problem: it is followed until the one time it is not, and
# then two of the four disagree in a way nobody notices until two themed
# things sit side by side.
#
# qtile IS NOT GENERATED. It reads the .conf directly in qtile/theme.py,
# because it can - it is Python. One fewer generated file to keep honest.
#
# GENERATED FILES ARE OVERWRITTEN WITHOUT ASKING and say so in their own first
# line. Anything hand-edited there is lost on the next run, which is why the
# header names the source file rather than just saying "generated".

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
THEMES="$HERE/themes"
STATE="${XDG_STATE_HOME:-$HOME/.local/state}/void-qtile"
CURRENT="$STATE/theme"

dry_run=false
args=()
for a in "$@"; do
    case "$a" in
        --dry-run) dry_run=true ;;
        *) args+=("$a") ;;
    esac
done
set -- "${args[@]:-}"

c_g=$'\033[1;32m'; c_r=$'\033[1;31m'; c_d=$'\033[2m'; c_0=$'\033[0m'
say() { printf '%s==>%s %s\n' "$c_g" "$c_0" "$*"; }
die() { printf '%stheme:%s %s\n' "$c_r" "$c_0" "$*" >&2; exit 1; }

# --- reading the palette -----------------------------------------------------
#
# Deliberately NOT `source`: this file is parsed by Python too, and a palette
# that can run shell code is a palette that has to be trusted. Only
# key=value lines are read, and the keys are constrained.
declare -A P
load() {
    local f="$1" line key value
    [[ -f "$f" ]] || die "no such theme file: $f"
    while IFS= read -r line; do
        # ONLY WHOLE-LINE COMMENTS - see the matching note in qtile/theme.py.
        # `line="${line%%#*}"` looks right and silently empties every colour,
        # because every value in this file starts with '#'.
        line="${line#"${line%%[![:space:]]*}"}"
        line="${line%"${line##*[![:space:]]}"}"
        [[ -z "$line" || "$line" == \#* ]] && continue
        [[ "$line" == *=* ]] || continue
        key="${line%%=*}"; value="${line#*=}"
        [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
        P["$key"]="$value"
    done < "$f"
}

v() { printf '%s' "${P[$1]:-}"; }
# foot wants colours with no leading '#'
vx() { printf '%s' "${P[$1]:-}" | tr -d '#'; }

current_theme() {
    [[ -f "$CURRENT" ]] && cat "$CURRENT" || echo nord
}

write() {
    local dst="$1"
    if $dry_run; then
        printf '    %swould write%s %s\n' "$c_d" "$c_0" "${dst/#$HOME/\~}"
        sed 's/^/        /'
        return 0
    fi
    mkdir -p "$(dirname "$dst")"
    cat > "$dst"
    printf '    wrote %s\n' "${dst/#$HOME/\~}"
}

# =============================================================================
# Generators
# =============================================================================

gen_foot() {
    write "$HERE/foot/foot.ini" <<EOF
# GENERATED BY bin/theme.sh FROM themes/$(v name).conf - DO NOT EDIT.
# Edit the palette and run bin/theme.sh again; this file is overwritten.
#
# foot wants colours WITHOUT the leading '#', which is the single most common
# way a foot colour config silently does nothing. theme.sh strips it.

# THE SECTION NAMES ARE foot 1.28's, NOT THE ONES EVERY EXAMPLE ON THE WEB
# SHOWS. foot gained light/dark theme switching and renamed [colors] to
# [colors-dark] / [colors-light]; the cursor colour moved INTO that section as
# `cursor=`, and selection became two keys rather than a [colors.selection]
# subsection. The old spelling does not warn, it refuses:
#
#     invalid section name: colors
#     [cursor].color: not a valid option: color
#
# initial-color-theme=dark so it starts on the one defined below rather than
# following whatever it would otherwise ask the system for.

[main]
font=monospace:size=$(v font_size)
pad=8x8
initial-color-theme=dark

[colors-dark]
alpha=1.0
foreground=$(vx term_fg)
background=$(vx term_bg)
cursor=$(vx term_cursor_fg) $(vx term_cursor_bg)
selection-foreground=$(vx term_sel_fg)
selection-background=$(vx term_sel_bg)

regular0=$(vx term_color0)
regular1=$(vx term_color1)
regular2=$(vx term_color2)
regular3=$(vx term_color3)
regular4=$(vx term_color4)
regular5=$(vx term_color5)
regular6=$(vx term_color6)
regular7=$(vx term_color7)

bright0=$(vx term_color8)
bright1=$(vx term_color9)
bright2=$(vx term_color10)
bright3=$(vx term_color11)
bright4=$(vx term_color12)
bright5=$(vx term_color13)
bright6=$(vx term_color14)
bright7=$(vx term_color15)
EOF
}

gen_dunst() {
    write "$HERE/dunst/dunstrc" <<EOF
# GENERATED BY bin/theme.sh FROM themes/$(v name).conf - DO NOT EDIT.
# Edit the palette and run bin/theme.sh again; this file is overwritten.

[global]
    # follow=none with an explicit monitor: this machine has one display, and
    # "follow the mouse" puts notifications wherever the pointer happens to be.
    follow = none
    monitor = 0

    origin = top-right
    offset = 12x48
    # 48 clears the 34px bar plus its margin, so a notification never lands on
    # top of the clock.

    width = (320, 520)
    height = (0, 300)
    scale = 0

    frame_width = 2
    corner_radius = 8
    gap_size = 6
    padding = 12
    horizontal_padding = 14

    font = $(v font) $(v font_size)
    markup = full
    format = "<b>%s</b>\\n%b"
    word_wrap = yes

    icon_position = left
    min_icon_size = 32
    max_icon_size = 64

    mouse_left_click = close_current
    mouse_middle_click = do_action
    mouse_right_click = close_all

[urgency_low]
    background = "$(v surface)"
    foreground = "$(v fg)"
    frame_color = "$(v dim)"
    timeout = 5

[urgency_normal]
    background = "$(v surface)"
    foreground = "$(v fgBright)"
    frame_color = "$(v accent)"
    timeout = 8

[urgency_critical]
    # NO TIMEOUT: a critical notification that disappears on its own is one you
    # were not at the machine to see.
    background = "$(v surface)"
    foreground = "$(v fgBright)"
    frame_color = "$(v danger)"
    timeout = 0
EOF
}

gen_gtk() {
    write "$HERE/gtk/settings.ini" <<EOF
# GENERATED BY bin/theme.sh FROM themes/$(v name).conf - DO NOT EDIT.
#
# gtk-application-prefer-dark-theme IS THE PART THAT MATTERS and the part most
# often left out: without it GTK renders its light variant regardless of the
# theme name, so file pickers come up white against a dark desktop.

[Settings]
gtk-theme-name=$(v gtk_theme)
gtk-application-prefer-dark-theme=$([[ "$(v appearance)" == dark ]] && echo 1 || echo 0)
gtk-icon-theme-name=$(v icon_theme)
gtk-cursor-theme-name=$(v cursor_theme)
gtk-cursor-theme-size=$(v cursor_size)
gtk-font-name=$(v font) $(v font_size)
EOF

    write "$HERE/gtk/gtk.css" <<EOF
/* GENERATED BY bin/theme.sh FROM themes/$(v name).conf - DO NOT EDIT.
 *
 * This is NOT a $(v name) GTK theme. No such theme is packaged for Void, so
 * this takes $(v gtk_theme) and overrides the colours GTK exposes as named
 * definitions.
 *
 * What it reaches: window backgrounds, selection, most text. What it does NOT
 * reach: widget internals drawn from the theme's own compiled stylesheet.
 * Expect the broad strokes to match and some details not to. */

@define-color theme_bg_color $(v bg);
@define-color theme_base_color $(v surface);
@define-color theme_fg_color $(v fg);
@define-color theme_text_color $(v fg);

@define-color theme_selected_bg_color $(v accent);
@define-color theme_selected_fg_color $(v accentFg);

@define-color insensitive_bg_color $(v surface);
@define-color insensitive_fg_color $(v dim);

@define-color borders $(v outline);
@define-color warning_color $(v warn);
@define-color error_color $(v danger);
@define-color success_color $(v ok);
EOF
}

# =============================================================================
# Commands
# =============================================================================

cmd="${1:-regen}"

case "$cmd" in
list)
    for f in "$THEMES"/*.conf; do
        n="$(basename "$f" .conf)"
        printf '  %-14s %s\n' "$n" "$([[ "$n" == "$(current_theme)" ]] && echo '(current)' || true)"
    done
    ;;

show)
    load "$THEMES/$(current_theme).conf"
    say "theme: $(v name)  ($(v appearance))"
    for k in bg fg accent surface dim ok warn danger gtk_theme cursor_theme cursor_size; do
        printf '  %-14s %s\n' "$k" "$(v "$k")"
    done
    ;;

set)
    name="${2:-}"
    [[ -n "$name" ]] || die "which theme? try: bin/theme.sh list"
    [[ -f "$THEMES/$name.conf" ]] || die "no theme '$name' in themes/"
    $dry_run || { mkdir -p "$STATE"; printf '%s' "$name" > "$CURRENT"; }
    say "theme set to $name"
    load "$THEMES/$name.conf"
    say "regenerating"
    gen_foot; gen_dunst; gen_gtk
    ;;

regen)
    load "$THEMES/$(current_theme).conf"
    say "regenerating from themes/$(v name).conf"
    gen_foot; gen_dunst; gen_gtk
    ;;

*)
    sed -n '2,20p' "$0"; exit 2 ;;
esac

if ! $dry_run && [[ "$cmd" == set || "$cmd" == regen ]]; then
    cat <<'NEXT'

  The generated files are in the repo. To put them where applications look:
    bin/link-dotfiles.sh

  To see the changes:
    foot      new windows only; existing ones keep the old colours
    dunst     pkill dunst
    GTK       restart the application
    qtile     qtile/reload.sh   (it reads themes/*.conf directly, not these)
NEXT
fi
